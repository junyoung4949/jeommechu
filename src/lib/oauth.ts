/**
 * 소셜 로그인 redirect_uri.
 *
 * OAuth 는 이 값을 **두 번** 쓴다 — 인가 요청 때 한 번(브라우저), 인가 코드를 토큰으로
 * 바꿀 때 또 한 번(서버). 공급자는 두 값이 **바이트 단위로 같을 것**을 요구한다.
 * 코드를 가로챈 쪽이 다른 주소로 토큰을 받아가는 걸 막는 장치다.
 *
 * 값을 정하는 건 브라우저의 origin 이라 서버가 미리 알 수 없다. 그래서 서버가 고정
 * 환경변수로 들고 있으면 환경이 하나일 때만 우연히 맞는다 — 실제로 그 구조 때문에
 * 로컬 개발에서 소셜 로그인이 전부 막혀 있었다.
 *
 * 이제 클라이언트가 이 값을 함께 보내고, 서버는 허용 목록으로 검증만 한다.
 *
 * **두 호출부가 반드시 같은 문자열을 만들어야 하므로 이 함수 하나만 쓴다.**
 * 각자 조립하면 슬래시 하나 차이로 어긋나고, 그때 공급자는 "인가 코드가 유효하지 않다"
 * 고만 말해서 원인이 보이지 않는다.
 */
export function oauthRedirectUri(provider: 'kakao' | 'google'): string {
  return `${window.location.origin}/oauth/${provider}`
}
